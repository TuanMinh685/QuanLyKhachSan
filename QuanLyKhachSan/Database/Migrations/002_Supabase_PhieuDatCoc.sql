-- PostgreSQL / Supabase: bổ sung sổ cọc, không xóa hay tạo lại dữ liệu hiện có.
BEGIN;
SET LOCAL lock_timeout = '10s';
CREATE TABLE IF NOT EXISTS PhieuDatCoc (
    MaPhieu integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    MaDatPhong integer NOT NULL REFERENCES DatPhong(MaDatPhong),
    LoaiGiaoDich varchar(10) NOT NULL CHECK (LoaiGiaoDich IN ('Thu', 'Hoan')),
    SoTien numeric(18,2) NOT NULL,
    PhuongThuc varchar(10) NOT NULL CHECK (PhuongThuc IN ('TM', 'CK', 'POS')),
    MaNhanVien integer NOT NULL REFERENCES NhanVien(MaNhanVien),
    NgayGiaoDich timestamp NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'Asia/Ho_Chi_Minh'),
    GhiChu varchar(200),
    CONSTRAINT CK_PhieuDatCoc_SoTien CHECK ((LoaiGiaoDich = 'Thu' AND SoTien > 0) OR (LoaiGiaoDich = 'Hoan' AND SoTien >= 0)),
    CONSTRAINT UQ_PhieuDatCoc_Don_Loai UNIQUE (MaDatPhong, LoaiGiaoDich)
);
-- Desktop kết nối trực tiếp bằng tài khoản DB; không mở bảng tiền cọc qua REST công khai.
ALTER TABLE PhieuDatCoc ENABLE ROW LEVEL SECURITY;
COMMIT;
